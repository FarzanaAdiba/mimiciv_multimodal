import pandas as pd
import numpy as np

admissions = pd.read_csv('/content/drive/MyDrive/MIMIC_IV_Pipeline/physionet.org/files/mimiciv/3.1/hosp/admissions.csv.gz', compression='gzip')
admissions.head()

#IN_PATH="/content/drive/MyDrive/MIMIC_IV_Pipeline/discharge.csv.gz"
IN_PATH="/content/drive/MyDrive/MIMIC_IV_Pipeline/radiology.csv.gz"
discharge_notes = pd.read_csv(IN_PATH, compression='gzip')
discharge_notes.head()

admissions['admittime'] = pd.to_datetime(admissions['admittime'])
admissions['dischtime'] = pd.to_datetime(admissions['dischtime'])
discharge_notes['charttime'] = pd.to_datetime(discharge_notes['charttime'])

print(f"✓ Admissions: {len(admissions)}")
#print(f"✓ Discharge notes: {len(discharge_notes)}")
print(f"✓ Radiology notes: {len(discharge_notes)}")

### STEP 2: MERGE AND CALCULATE DAY BINS ###
print("\n[Step 2] Calculating day bins...")
discharge_with_admit = discharge_notes.merge(
    admissions[['subject_id', 'hadm_id', 'admittime', 'dischtime']],
    on=['subject_id', 'hadm_id'],
    how='left'
)

discharge_with_admit['hours_from_admission'] = (
    discharge_with_admit['charttime'] - discharge_with_admit['admittime']
).dt.total_seconds() / 3600

discharge_with_admit['days_from_admission'] = discharge_with_admit['hours_from_admission'] / 24
discharge_with_admit['day_bin'] = discharge_with_admit['days_from_admission'].apply(
    lambda x: int(np.floor(x)) if pd.notna(x) and x >= 0 else -1
)

discharge_during_admission = discharge_with_admit[discharge_with_admit['day_bin'] >= 0]
print(f"✓ Notes during admission: {len(discharge_during_admission)}")

### STEP 3: COUNT NOTES PER DAY ###
print("\n[Step 3] Counting radiology notes per day...")
notes_per_day = discharge_during_admission.groupby(
    ['subject_id', 'hadm_id', 'day_bin']
).size().reset_index(name='note_count')

#print(f"\nMaximum discharge notes per day: {notes_per_day['note_count'].max()}")
print(f"Max radiology notes per day: {notes_per_day['note_count'].max():.2f}")
print(f"95th percentile: {int(notes_per_day['note_count'].quantile(0.95))}")
print(f"99th percentile: {int(notes_per_day['note_count'].quantile(0.99))}")

# Update MAX_DISCHARGE_NOTES_PER_DAY based on results
MAX_DISCHARGE_NOTES_PER_DAY = max(3, int(notes_per_day['note_count'].quantile(0.99)) + 1)
print(f"\n➜ Using {MAX_DISCHARGE_NOTES_PER_DAY} columns for discharge notes")

### STEP 4: CREATE FILE PATHS ###
print("\n[Step 4] Creating file paths...")
discharge_with_admit['note_file_path'] = (
    'notes/discharge/' +
    discharge_with_admit['subject_id'].astype(str) + '/' +
    discharge_with_admit['note_id'].astype(str) + '.txt'
)

# Re-filter discharge_during_admission to include the new 'note_file_path' column
discharge_during_admission = discharge_with_admit[discharge_with_admit['day_bin'] >= 0]

### STEP 5: GROUP AND CREATE FIXED COLUMNS ###
print("\n[Step 5] Creating fixed-column format...")
discharge_with_admit_sorted = discharge_during_admission.sort_values(
    ['subject_id', 'hadm_id', 'day_bin', 'charttime']
)

daywise_discharge = discharge_with_admit_sorted.groupby(
    ['subject_id', 'hadm_id', 'day_bin']
).agg({
    'note_file_path': lambda x: list(x),
    'note_id': lambda x: list(x),
    'charttime': 'min'
}).reset_index()

print(f"Grouped into {len(daywise_discharge)} day-level records")

# Create fixed columns
for i in range(1, MAX_DISCHARGE_NOTES_PER_DAY + 1):
    daywise_discharge[f'discharge_note_{i}'] = daywise_discharge['note_file_path'].apply(
        lambda x: x[i-1] if len(x) >= i else None
    )
    daywise_discharge[f'discharge_note_id_{i}'] = daywise_discharge['note_id'].apply(
        lambda x: x[i-1] if len(x) >= i else None
    )

# Drop the list columns
daywise_discharge = daywise_discharge.drop(columns=['note_file_path', 'note_id'])

### STEP 5: MERGE WITH ADMISSION METADATA ###
print("\n[Step 5] Adding admission metadata...")
daywise_discharge_full = daywise_discharge.merge(
    admissions[['subject_id', 'hadm_id', 'admittime', 'dischtime',
                'admission_type', 'insurance', 'race', 'hospital_expire_flag']],
    on=['subject_id', 'hadm_id'],
    how='left'
)

### STEP 6: VALIDATION ###
print("\n[Step 6] Validation...")
note_cols = [f'discharge_note_{i}' for i in range(1, MAX_DISCHARGE_NOTES_PER_DAY + 1)]
print("\nColumn fill rates:")
for col in note_cols:
    filled = daywise_discharge_full[col].notna().sum()
    print(f"  {col}: {100*filled/len(daywise_discharge_full):.1f}%")

### STEP 7: SAVE ###
print("\n[Step 7] Saving...")
daywise_discharge_full.to_csv('mimic_daywise_discharge_notes.csv', index=False)
print("Saved csv: mimic_daywise_discharge_notes.csv")

print("\n" + "="*70)
print("SUMMARY")
print("="*70)
print(f"Total day-level records: {len(daywise_discharge_full)}")
print(f"Unique admissions: {daywise_discharge_full['hadm_id'].nunique()}")
print(f"Unique patients: {daywise_discharge_full['subject_id'].nunique()}")
print(f"Columns: {len(daywise_discharge_full.columns)}")
print(f"Discharge note columns: {MAX_DISCHARGE_NOTES_PER_DAY}")

